def _sync_invigilator_users_to_allocation_pool(db: DatabaseConnection) -> None:
    db.execute(
        """
        INSERT INTO allocation_invigilators (username)
        SELECT username
        FROM users
        WHERE role = 'invigilator'
        ON CONFLICT (username) DO NOTHING
        """
    )


def clear_expired_timetables(db: DatabaseConnection | None = None) -> None:
    if db is None:
        with get_connection() as connection:
            clear_expired_timetables(connection)
        return

    settings = db.execute(
        "SELECT exam_end_date FROM allocation_settings WHERE id = 1"
    ).fetchone()
    if settings is not None and date.today() > date.fromisoformat(settings["exam_end_date"]):
        db.execute("DELETE FROM timetables")
