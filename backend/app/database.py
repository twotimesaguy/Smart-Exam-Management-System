import os
from contextlib import contextmanager
from datetime import date
from pathlib import Path
from typing import Any, Iterator, Sequence

import psycopg
from dotenv import load_dotenv
from psycopg.rows import dict_row

load_dotenv(Path(__file__).resolve().parents[1] / ".env")

BASE_DIR = Path(__file__).resolve().parents[1]
DATABASE_URL = os.getenv("DATABASE_URL")


class DatabaseConnection:
    """Small adapter that keeps the existing repository SQL readable.

    The API originally used SQLite's ``?`` placeholders. Psycopg uses ``%s``;
    this adapter translates them at the database boundary while all queries use
    PostgreSQL underneath.
    """

    def __init__(self, connection: psycopg.Connection[Any]) -> None:
        self._connection = connection

    def execute(self, query: str, parameters: Sequence[Any] | None = None):
        return self._connection.execute(
            query.replace("?", "%s"),
            parameters if parameters is not None else (),
        )

    def executemany(self, query: str, parameters: Sequence[Sequence[Any]]) -> None:
        with self._connection.cursor() as cursor:
            cursor.executemany(query.replace("?", "%s"), parameters)

    def commit(self) -> None:
        self._connection.commit()

    def rollback(self) -> None:
        self._connection.rollback()

    def close(self) -> None:
        self._connection.close()


@contextmanager
def get_connection() -> Iterator[DatabaseConnection]:
    if not DATABASE_URL:
        raise RuntimeError(
            "DATABASE_URL is not configured. Add a PostgreSQL database URL to backend/.env "
            "locally or set Railway's DATABASE_URL variable before deploying."
        )

    connection = psycopg.connect(DATABASE_URL, row_factory=dict_row)
    db = DatabaseConnection(connection)
    try:
        yield db
        db.commit()
    except Exception:
        db.rollback()
        raise
    finally:
        db.close()


def init_db() -> None:
    """Create and update the PostgreSQL schema required by the API."""
    with get_connection() as db:
        db.execute(
            """
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username TEXT NOT NULL UNIQUE,
                password_hash TEXT NOT NULL,
                role TEXT NOT NULL CHECK(role IN ('admin', 'invigilator', 'disciplinary_officer')),
                profile_image_path TEXT,
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text
            );

            CREATE TABLE IF NOT EXISTS students (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                student_id TEXT NOT NULL UNIQUE,
                full_name TEXT NOT NULL,
                programme TEXT NOT NULL,
                level TEXT NOT NULL,
                face_image_path TEXT,
                face_embedding TEXT,
                registered_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text
            );

            CREATE TABLE IF NOT EXISTS timetables (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                title TEXT NOT NULL,
                exam_period TEXT NOT NULL,
                generated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text
            );

            CREATE TABLE IF NOT EXISTS timetable_entries (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                timetable_id INTEGER NOT NULL REFERENCES timetables(id) ON DELETE CASCADE,
                course_code TEXT NOT NULL,
                course_title TEXT NOT NULL,
                exam_date TEXT NOT NULL,
                start_time TEXT NOT NULL,
                end_time TEXT NOT NULL,
                venue TEXT NOT NULL,
                student_level TEXT NOT NULL,
                student_count INTEGER NOT NULL CHECK(student_count > 0),
                invigilator_username TEXT NOT NULL
            );

            CREATE TABLE IF NOT EXISTS assignments (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                timetable_entry_id INTEGER NOT NULL REFERENCES timetable_entries(id) ON DELETE CASCADE,
                invigilator_username TEXT NOT NULL,
                status TEXT NOT NULL DEFAULT 'pending'
                    CHECK(status IN ('pending', 'accepted', 'in_progress', 'completed'))
            );

            CREATE TABLE IF NOT EXISTS allocation_courses (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                course_code TEXT NOT NULL UNIQUE,
                course_title TEXT NOT NULL,
                student_level TEXT NOT NULL,
                student_count INTEGER NOT NULL CHECK(student_count > 0),
                duration_minutes INTEGER NOT NULL CHECK(duration_minutes > 0)
            );

            CREATE TABLE IF NOT EXISTS allocation_venues (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL UNIQUE,
                capacity INTEGER NOT NULL CHECK(capacity > 0)
            );

            CREATE TABLE IF NOT EXISTS allocation_invigilators (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username TEXT NOT NULL UNIQUE
            );

            CREATE TABLE IF NOT EXISTS allocation_settings (
                id INTEGER PRIMARY KEY CHECK(id = 1),
                title TEXT NOT NULL,
                exam_period TEXT NOT NULL,
                exam_start_date TEXT NOT NULL,
                exam_end_date TEXT NOT NULL,
                start_times TEXT NOT NULL
            );

            CREATE TABLE IF NOT EXISTS attendance_records (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                student_id TEXT NOT NULL,
                full_name TEXT NOT NULL,
                course_title TEXT NOT NULL DEFAULT '',
                course_code TEXT NOT NULL,
                venue TEXT NOT NULL,
                recorded_by TEXT NOT NULL,
                confidence DOUBLE PRECISION,
                exam_date TEXT NOT NULL DEFAULT CURRENT_DATE::text,
                recorded_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text
            );

            CREATE TABLE IF NOT EXISTS malpractice_reports (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                student_id TEXT NOT NULL,
                student_level TEXT NOT NULL,
                course_title TEXT NOT NULL,
                course_code TEXT NOT NULL,
                venue TEXT NOT NULL,
                invigilator_name TEXT NOT NULL,
                incident_description TEXT NOT NULL,
                student_statement TEXT NOT NULL,
                student_face_image_path TEXT,
                foreign_material_image_path TEXT,
                student_statement_audio BYTEA,
                student_statement_audio_content_type TEXT,
                student_statement_audio_filename TEXT,
                forwarded_status TEXT NOT NULL DEFAULT 'pending',
                forwarded_error TEXT,
                case_status TEXT NOT NULL DEFAULT 'pending'
                    CHECK(case_status IN ('pending', 'under_review', 'resolved', 'dismissed')),
                resolution_notes TEXT NOT NULL DEFAULT '',
                handled_by TEXT,
                handled_at TEXT,
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP::text
            );

            CREATE INDEX IF NOT EXISTS idx_attendance_course_code
                ON attendance_records(course_code);
            CREATE INDEX IF NOT EXISTS idx_assignments_invigilator
                ON assignments(invigilator_username);
            """
        )
        _add_missing_columns(db)
        _seed_allocation_setup(db)
        _sync_invigilator_users_to_allocation_pool(db)
        clear_expired_timetables(db)


def _add_missing_columns(db: DatabaseConnection) -> None:
    """Keep existing PostgreSQL deployments compatible with newer API fields."""
    db.execute("ALTER TABLE users ADD COLUMN IF NOT EXISTS profile_image_path TEXT")
    db.execute(
        "ALTER TABLE attendance_records ADD COLUMN IF NOT EXISTS course_title TEXT NOT NULL DEFAULT ''"
    )
    db.execute(
        "ALTER TABLE attendance_records ADD COLUMN IF NOT EXISTS exam_date TEXT NOT NULL DEFAULT CURRENT_DATE::text"
    )
    db.execute(
        "ALTER TABLE malpractice_reports ADD COLUMN IF NOT EXISTS case_status TEXT NOT NULL DEFAULT 'pending'"
    )
    db.execute(
        "ALTER TABLE malpractice_reports ADD COLUMN IF NOT EXISTS resolution_notes TEXT NOT NULL DEFAULT ''"
    )
    db.execute("ALTER TABLE malpractice_reports ADD COLUMN IF NOT EXISTS handled_by TEXT")
    db.execute("ALTER TABLE malpractice_reports ADD COLUMN IF NOT EXISTS handled_at TEXT")
    db.execute("ALTER TABLE malpractice_reports ADD COLUMN IF NOT EXISTS student_statement_audio BYTEA")
    db.execute(
        "ALTER TABLE malpractice_reports ADD COLUMN IF NOT EXISTS student_statement_audio_content_type TEXT"
    )
    db.execute(
        "ALTER TABLE malpractice_reports ADD COLUMN IF NOT EXISTS student_statement_audio_filename TEXT"
    )


